import com.qualcomm.robotcore.eventloop.opmode.TeleOp;
import com.qualcomm.robotcore.hardware.DcMotor;
import com.qualcomm.robotcore.hardware.DcMotorEx;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.teamcode.fissionlib.input.FoozPad;
import org.firstinspires.ftc.teamcode.pedroPathing.follower.Follower;


@TeleOp
public class SimpleMecanumBase extends OpMode {

    // Use FTCLib's built in mecanum drivetrain class
    private Follower follower;

    private DcMotorEx leftFront;
    private DcMotorEx leftRear;
    private DcMotorEx rightFront;
    private DcMotorEx rightRear;
    // easier to reset heading than IMu, also counteracts imu drift
    double headingOffset = 0;

    @Override
    public void init() {
        follower = new Follower(hardwareMap);

        leftFront = hardwareMap.get(DcMotorEx.class, leftFrontMotorName);
        leftRear = hardwareMap.get(DcMotorEx.class, leftRearMotorName);
        rightRear = hardwareMap.get(DcMotorEx.class, rightRearMotorName);
        rightFront = hardwareMap.get(DcMotorEx.class, rightFrontMotorName);

        leftFront.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
        leftRear.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
        rightRear.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
        rightFront.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);

        follower.startTeleopDrive();
    }

    @Override
    public void loop() {
        double y = -gamepad1.left_stick_y/2;
        double x = -gamepad1.left_stick_x * .4;
        double r = -gamepad1.right_stick_x * .4;

        y = y * (1+gamepad1.right_trigger*.4) * (1-gamepad1.left_trigger);
        x = x * (1+gamepad1.right_trigger*.4) * (1-gamepad1.left_trigger);
        r = r * (1+gamepad1.right_trigger*.4) * (1-gamepad1.left_trigger);

        follower.setTeleOpMovementVectors(y, x, r);
        follower.update();
    }
}
